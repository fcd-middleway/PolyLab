// PolyLab Web App Entry Point
import { Header } from './components/Header';
import { Toolbar } from './components/Toolbar';
import { MeshPanel } from './components/MeshPanel';
import { PropertiesPanel } from './components/PropertiesPanel';
import { StatusBar } from './components/StatusBar';
import { ViewerCanvas } from './components/ViewerCanvas';
import { ProjectManager } from './core/ProjectManager';
import { UIManager } from './core/UIManager';
import { ViewerProject } from './projects/ViewerProject';
import { PerlinProject } from './projects/PerlinProject';
import { RoverProject } from './projects/RoverProject';
import { CameraControls } from './utils/cameraControls';
import { appLogger, viewerLogger } from './utils/logger';

// Import styles
import './styles/main.css';
import './styles/header.css';
import './styles/toolbar.css';
import './styles/panels.css';
import './styles/statusbar.css';
import './styles/help.css';

/**
 * Initialize the UI components
 */
function initializeUI() {
    appLogger.info('Initializing UI components...');
    
    const app = document.getElementById('app')!;
    
    // Create components
    const header = new Header();
    const toolbar = new Toolbar();
    const meshPanel = new MeshPanel();
    const viewerCanvas = new ViewerCanvas();
    const detailsPanel = new PropertiesPanel();
    const statusBar = new StatusBar();

    // Build layout
    const mainContent = document.createElement('div');
    mainContent.className = 'main-content';
    mainContent.id = 'main-content';
    
    mainContent.appendChild(meshPanel.element);
    mainContent.appendChild(viewerCanvas.element);
    mainContent.appendChild(detailsPanel.element);

    app.appendChild(header.element);
    app.appendChild(toolbar.element);
    app.appendChild(mainContent);
    app.appendChild(statusBar.element);

    appLogger.info('UI components initialized successfully');
    
    return {
        header,
        toolbar,
        meshPanel,
        viewerCanvas,
        detailsPanel,
        statusBar
    };
}

/**
 * Initialize WebGPU viewer
 * 
 * @returns The viewer handle for interaction
 */
async function initializeViewer(canvas: HTMLCanvasElement, statusBar: StatusBar) {
    try {
        viewerLogger.info('Starting viewer initialization...');
        statusBar.updateStats({ status: 'Loading WebAssembly module...' });

        // Import the WASM module (generated by wasm-pack)
        viewerLogger.debug('Importing WASM module...');
        const wasmModule = await import('../../../crates/polylab-viewer/pkg/polylab_viewer.js');
        await wasmModule.default();
        viewerLogger.debug('WASM module loaded successfully');

        statusBar.updateStats({ status: 'Creating viewer...' });

        // Create viewer instance
        viewerLogger.debug('Creating ViewerHandle instance...');
        const viewer = await wasmModule.ViewerHandle.create('webgpu-canvas');
        viewerLogger.info('ViewerHandle created successfully');

        statusBar.updateStats({ 
            status: '✅ Ready',
            backend: 'WebGPU'
        });

        viewerLogger.info('Viewer initialized successfully');

        // Return viewer handle
        return viewer;

    } catch (error) {
        viewerLogger.error('Failed to initialize viewer', { error });
        statusBar.updateStats({ status: `❌ Error: ${error}` });

        // Check if WebGPU is supported
        if (!navigator.gpu) {
            viewerLogger.error('WebGPU not supported');
            statusBar.updateStats({ 
                status: '❌ WebGPU not supported. Use Chrome 113+ or Edge 113+' 
            });
        }
        
        throw error;
    }
}

/**
 * Main application entry point
 */
async function main() {
    appLogger.info('Starting PolyLab application...');
    
    // Check WebGPU support
    if (!navigator.gpu) {
        appLogger.error('WebGPU not supported in this browser');
        alert('❌ WebGPU is not supported in this browser.\n\nPlease use:\n- Chrome 113+\n- Edge 113+\n- Firefox Nightly with WebGPU enabled');
        return;
    }

    // Initialize UI
    const ui = initializeUI();

    // Initialize WebGPU viewer
    const canvas = ui.viewerCanvas.getCanvas();
    
    // Auto-resize canvas to fit container
    ui.viewerCanvas.autoResize();
    
    try {
        const viewer = await initializeViewer(canvas, ui.statusBar);

        // ========================
        // Camera Controls Setup
        // ========================
        const cameraControls = new CameraControls(viewer);
        cameraControls.enable();
        appLogger.info('Camera controls enabled');

        // ========================
        // Project System Setup
        // ========================
        appLogger.info('Initializing project system...');

        // Create ProjectManager and set viewer
        const projectManager = new ProjectManager();
        projectManager.setViewer(viewer);

        // Create UIManager with panel references
        const uiManager = new UIManager(ui.toolbar, ui.meshPanel, ui.detailsPanel);

        // Create ViewerProject
        const viewerProject = new ViewerProject();
        
        // Inject UI components into ViewerProject
        viewerProject.setUIComponents(ui.meshPanel, ui.detailsPanel, ui.statusBar);
        
        // Initialize ViewerProject with viewer
        await viewerProject.init(viewer);
        
        // Register ViewerProject
        projectManager.registerProject(viewerProject);
        appLogger.info('ViewerProject registered');

        // Create PerlinProject
        const perlinProject = new PerlinProject();
        
        // Inject UI components into PerlinProject
        perlinProject.setUIComponents(ui.meshPanel, ui.statusBar, ui.detailsPanel);
        
        // Register PerlinProject (will be initialized when activated)
        projectManager.registerProject(perlinProject);
        appLogger.info('PerlinProject registered');

        // Create RoverProject
        const roverProject = new RoverProject();
        
        // Inject UI components into RoverProject
        roverProject.setUIComponents(ui.meshPanel, ui.statusBar, ui.detailsPanel);
        
        // Register RoverProject (will be initialized when activated)
        projectManager.registerProject(roverProject);
        appLogger.info('RoverProject registered');

        // Configure header with available projects
        const projects = projectManager.getProjects();
        ui.header.setProjects(projects.map(p => ({
            id: p.getId(),
            name: p.getName(),
            icon: p.getConfig().icon || '📦'
        })));

        // Connect header to ProjectManager for project switching
        ui.header.setOnProjectChange(async (projectId: string) => {
            appLogger.info('Switching project', { projectId });
            try {
                await projectManager.switchToProject(projectId);
            } catch (error) {
                appLogger.error('Failed to switch project', { projectId, error });
            }
        });

        // Connect ProjectManager to UIManager for UI updates
        projectManager.setOnProjectChange((project) => {
            ui.header.setActiveProject(project.getId());
            uiManager.applyConfig(project.getConfig());
            appLogger.debug('UI updated for project', { projectId: project.getId() });
        });

        // Activate default project (Viewer)
        await projectManager.switchToProject('viewer');
        appLogger.info('Default project activated');

        // ========================
        // Animation Loop
        // ========================
        let frameCount = 0;
        let lastTime = performance.now();

        function animate() {
            try {
                const currentTime = performance.now();
                const deltaTime = (currentTime - lastTime) / 1000; // in seconds

                // Update camera controls
                cameraControls.update(deltaTime);
                
                // Render viewer
                viewer.render();
                
                // Update active project
                projectManager.update(deltaTime);
                
                // Update FPS counter
                frameCount++;
                if (currentTime - lastTime >= 1000) {
                    const fps = Math.round(frameCount * 1000 / (currentTime - lastTime));
                    ui.statusBar.updateStats({ fps });
                    frameCount = 0;
                    lastTime = currentTime;
                }

                requestAnimationFrame(animate);
            } catch (e) {
                viewerLogger.error('Render error', { error: e });
                ui.statusBar.updateStats({ status: `❌ Error: ${e}` });
            }
        }

        animate();
        appLogger.info('Animation loop started');

        appLogger.info('Application initialized successfully');
    } catch (error) {
        appLogger.error('Failed to initialize application', { error });
    }
}

// Start the application
main();

